export function applyTemplateSwitch(id: TemplateId, prev: CreativeData): CreativeData {
  const preset = TEMPLATE_PRESETS[id]
  const fresh = defaultCreativeData()
  const brand = Object.fromEntries(BRAND_PRESERVE_KEYS.map((k) => [k, prev[k]])) as Partial<CreativeData>
  return {
    ...fresh,
    ...(preset ?? {}),
    templateId: id,
    ...brand,
    accentColor: preset?.accentColor ?? prev.accentColor,
    secondaryColor: preset?.secondaryColor ?? prev.secondaryColor,
    highlightStyle: preset?.highlightStyle ?? prev.highlightStyle,
    highlightColor: preset?.highlightColor ?? prev.highlightColor,
    category: preset?.category ?? prev.category,
  }
}

export function applyCategoryPreset(category: ContentCategory): CreativeData {
  const base = defaultCreativeData()
  const preset = CATEGORY_PRESETS[category]
  return { ...base, ...preset, category }
}
